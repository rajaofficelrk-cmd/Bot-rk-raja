function makePool(base, endings, total) {
  const result = [];
  const used = new Set();

  // Original messages first
  for (const item of base) {
    if (!used.has(item)) {
      used.add(item);
      result.push(item);
    }
  }

  let round = 1;

  // Generate many distinct variations.
  while (result.length < total) {
    for (let i = 0; i < base.length && result.length < total; i++) {
      for (let j = 0; j < endings.length && result.length < total; j++) {

        const original = base[i];
        const emoji = endings[j];

        let variation;

        if (round % 5 === 0) {
          variation = `${original}\n${emoji}`;
        } else if (round % 3 === 0) {
          variation = `${original} ${emoji}`;
        } else if (round % 2 === 0) {
          variation = `${emoji} ${original}`;
        } else {
          variation = `${original}${emoji}`;
        }

        if (!used.has(variation)) {
          used.add(variation);
          result.push(variation);
        }
      }
    }

    round++;

    // Safety guard
    if (round > 1000) break;
  }

  return result.slice(0, total);
}

